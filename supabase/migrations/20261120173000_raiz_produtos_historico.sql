-- Raiz Ancestral V12: HISTÓRICO DE ALTERAÇÕES (PREPARADO; NÃO EXECUTADO).
-- ATENÇÃO: esta migration NÃO deve ser aplicada no banco principal sem aprovação.
-- Ela registra INSERT/UPDATE/DELETE dos produtos e permite leitura só ao administrador.
-- Toda a autorização de mutação de produtos permanece nas políticas RLS existentes.
BEGIN;
CREATE TABLE IF NOT EXISTS public.raiz_produtos_historico (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 produto_id bigint NOT NULL,
 operacao text NOT NULL CHECK (operacao IN ('INSERT','UPDATE','DELETE')),
 antes jsonb,
 depois jsonb,
 alterado_por uuid,
 alterado_em timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS raiz_produtos_historico_produto_idx
 ON public.raiz_produtos_historico (produto_id,alterado_em DESC);
ALTER TABLE public.raiz_produtos_historico ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.raiz_produtos_historico FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.raiz_produtos_historico TO authenticated;
DROP POLICY IF EXISTS raiz_historico_select_admin ON public.raiz_produtos_historico;
CREATE POLICY raiz_historico_select_admin
 ON public.raiz_produtos_historico FOR SELECT TO authenticated
 USING ((select public.is_raiz_admin()));

CREATE OR REPLACE FUNCTION public.raiz_registrar_historico_produto()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $body$
BEGIN
 IF TG_OP = 'INSERT' THEN
   INSERT INTO public.raiz_produtos_historico(produto_id,operacao,antes,depois,alterado_por)
   VALUES (NEW.id,'INSERT',NULL,to_jsonb(NEW),auth.uid());
   RETURN NEW;
 ELSIF TG_OP = 'UPDATE' THEN
   IF to_jsonb(OLD) IS DISTINCT FROM to_jsonb(NEW) THEN
     INSERT INTO public.raiz_produtos_historico(produto_id,operacao,antes,depois,alterado_por)
     VALUES (NEW.id,'UPDATE',to_jsonb(OLD),to_jsonb(NEW),auth.uid());
   END IF;
   RETURN NEW;
 ELSE
   INSERT INTO public.raiz_produtos_historico(produto_id,operacao,antes,depois,alterado_por)
   VALUES (OLD.id,'DELETE',to_jsonb(OLD),NULL,auth.uid());
   RETURN OLD;
 END IF;
END;
$body$;
REVOKE ALL ON FUNCTION public.raiz_registrar_historico_produto() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS raiz_produtos_audit_trg ON public.produtos;
CREATE TRIGGER raiz_produtos_audit_trg
 AFTER INSERT OR UPDATE OR DELETE ON public.produtos
 FOR EACH ROW EXECUTE FUNCTION public.raiz_registrar_historico_produto();
COMMIT;

